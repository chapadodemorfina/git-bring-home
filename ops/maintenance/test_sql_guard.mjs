import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

// Install the optional PostgreSQL test runtime outside the application tree:
// npm install --prefix /tmp/i9-maintenance-test-runtime --no-save @electric-sql/pglite@0.5.10
// PGLITE_MODULE_PATH=/tmp/i9-maintenance-test-runtime/node_modules/@electric-sql/pglite/dist/index.js \
//   node ops/maintenance/test_sql_guard.mjs
const { PGlite } = await import(process.env.PGLITE_MODULE_PATH || '@electric-sql/pglite');
const cleanup = await readFile(new URL('./cleanup_internal_logs.sql', import.meta.url), 'utf8');
const inspection = await readFile(new URL('./inspect_internal_logs.sql', import.meta.url), 'utf8');
const db = new PGlite();
let passed = 0;

// The stub models the named scheduling API only. The extension worker itself is
// not installed, invoked, or represented by these tests.
const schedulingStub = `CREATE OR REPLACE FUNCTION cron.schedule(
  job_name text, cron_expression text, sql_command text
) RETURNS bigint LANGUAGE plpgsql AS $stub$
DECLARE result_id bigint;
BEGIN
  INSERT INTO cron.job (jobname, schedule, command, active, database, username)
  VALUES (job_name, cron_expression, sql_command, true, current_database(), current_user)
  ON CONFLICT (jobname, username) DO UPDATE
    SET schedule = EXCLUDED.schedule, command = EXCLUDED.command, active = true
  RETURNING jobid INTO result_id;
  RETURN result_id;
END;
$stub$;`;

async function test(name, run) {
  await run();
  passed += 1;
  console.log(`ok ${passed} - ${name}`);
}

async function rows(query) {
  return (await db.query(query)).rows;
}

async function preservedState() {
  return {
    business: await rows('SELECT * FROM public.business_probe ORDER BY id'),
    notifications: await rows('SELECT * FROM public.notification_probe ORDER BY id'),
    jobs: await rows(`SELECT * FROM cron.job
      WHERE jobname <> 'daily-cleanup-internal-logs' ORDER BY jobid`),
    sequences: await rows(`SELECT schemaname, sequencename, last_value FROM pg_sequences
      WHERE sequencename <> 'job_jobid_seq' ORDER BY schemaname, sequencename`),
  };
}

async function logState() {
  return {
    cron: await rows('SELECT * FROM cron.job_run_details ORDER BY runid'),
    http: await rows('SELECT * FROM net._http_response ORDER BY id'),
  };
}

try {
  await db.exec(`CREATE SCHEMA cron;
    CREATE SCHEMA net;
    CREATE SCHEMA extensions;
    CREATE TABLE cron.job (
      jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      jobname text NOT NULL, schedule text NOT NULL, command text NOT NULL,
      active boolean NOT NULL, database text NOT NULL, username text NOT NULL,
      UNIQUE (jobname, username)
    );
    CREATE TABLE cron.job_run_details (
      runid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      status text, end_time timestamptz, marker text
    );
    CREATE TABLE net._http_response (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created timestamptz, marker text
    );
    CREATE TABLE public.business_probe (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload text
    );
    CREATE TABLE public.notification_probe (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pending boolean
    );
    INSERT INTO public.business_probe (payload) VALUES ('business-sentinel');
    INSERT INTO public.notification_probe (pending) VALUES (true);
    INSERT INTO cron.job (jobname, schedule, command, active, database, username)
    VALUES ('process-notifications-every-minute', '* * * * *',
      'SELECT 314159 /* notification-job-sentinel */', true, current_database(), current_user);
    INSERT INTO cron.job_run_details (status, end_time, marker)
    VALUES ('running', NULL, 'cron-secret-sentinel'), ('succeeded', now(), 'recent');
    INSERT INTO net._http_response (created, marker) VALUES (now(), 'http-secret-sentinel');
    CREATE FUNCTION extensions.grant_pg_cron_access() RETURNS void LANGUAGE plpgsql AS
      'BEGIN PERFORM 1 FROM cron.job_run_details; END;';
    CREATE VIEW public.log_consumer AS SELECT * FROM cron.job_run_details;`);
  await db.exec(schedulingStub);

  await test('full cleanup removes only the two logs despite textual consumers and active history', async () => {
    const before = await preservedState();
    const result = await db.exec(cleanup);
    assert.deepEqual(await logState(), { cron: [], http: [] });
    assert.deepEqual(await preservedState(), before,
      'business rows, pending notifications, notification cron, and log sequences must be preserved');
    assert.equal((await rows("SELECT to_regprocedure('extensions.grant_pg_cron_access()') IS NOT NULL AS present"))[0].present, true);
    assert.deepEqual(await rows('SELECT * FROM public.log_consumer'), []);
    const reports = result.flatMap((entry) => entry.rows || []).filter((row) => row.maintenance_result);
    assert.equal(reports.length, 1);
    assert.equal(reports[0].maintenance_result.relations.length, 2);
    assert.doesNotMatch(JSON.stringify(result), /notification-job-sentinel|cron-secret-sentinel|http-secret-sentinel/);
  });

  await test('reapplying the full SQL keeps one named retention job and preserves notification scheduling', async () => {
    const before = await preservedState();
    const first = await rows("SELECT * FROM cron.job WHERE jobname = 'daily-cleanup-internal-logs'");
    assert.equal(first.length, 1);
    assert.equal(first[0].schedule, '0 6 * * *');
    assert.equal(first[0].active, true);
    await db.exec(cleanup);
    const second = await rows("SELECT * FROM cron.job WHERE jobname = 'daily-cleanup-internal-logs'");
    assert.deepEqual(second, first);
    assert.deepEqual(await preservedState(), before);
  });

  await test('scheduled SQL deletes completed logs older than three days and preserves unfinished/recent rows', async () => {
    const [{ command }] = await rows("SELECT command FROM cron.job WHERE jobname = 'daily-cleanup-internal-logs'");
    await db.exec(`BEGIN;
      INSERT INTO cron.job_run_details (status, end_time, marker) VALUES
        ('succeeded', now() - interval '4 days', 'old-success'),
        ('failed', now() - interval '4 days', 'old-failure'),
        ('succeeded', now() - interval '2 days', 'recent'),
        ('succeeded', now() - interval '3 days', 'boundary'),
        ('running', NULL, 'unfinished'),
        ('running', now() - interval '4 days', 'running-old'),
        ('succeeded', NULL, 'missing-end'),
        ('unknown', now() - interval '4 days', 'unknown');
      INSERT INTO net._http_response (created, marker) VALUES
        (now() - interval '4 days', 'old'),
        (now() - interval '2 days', 'recent'),
        (now() - interval '3 days', 'boundary'),
        (NULL, 'missing-created');`);
    try {
      const before = await preservedState();
      await db.exec(command);
      assert.deepEqual(await rows('SELECT marker FROM cron.job_run_details ORDER BY marker'),
        ['boundary', 'missing-end', 'recent', 'running-old', 'unfinished', 'unknown'].map((marker) => ({ marker })));
      assert.deepEqual(await rows('SELECT marker FROM net._http_response ORDER BY marker'),
        ['boundary', 'missing-created', 'recent'].map((marker) => ({ marker })));
      assert.deepEqual(await preservedState(), before);
    } finally {
      await db.exec('ROLLBACK');
    }
  });

  await test('scheduling failure rolls back the preceding truncation and preserves existing jobs', async () => {
    await db.exec(`INSERT INTO cron.job_run_details (status, end_time, marker)
      VALUES ('succeeded', now(), 'rollback-cron');
      INSERT INTO net._http_response (created, marker) VALUES (now(), 'rollback-http');
      CREATE OR REPLACE FUNCTION cron.schedule(job_name text, cron_expression text, sql_command text)
      RETURNS bigint LANGUAGE plpgsql AS $stub$
      BEGIN RAISE EXCEPTION 'simulated scheduling failure'; END;
      $stub$;`);
    const before = await logState();
    const unchanged = await preservedState();
    const jobs = await rows('SELECT * FROM cron.job ORDER BY jobid');
    await assert.rejects(db.exec(cleanup), (error) =>
      error.code === 'P0001' && error.message === 'simulated scheduling failure');
    await db.exec('ROLLBACK');
    assert.deepEqual(await logState(), before);
    assert.deepEqual(await preservedState(), unchanged);
    assert.deepEqual(await rows('SELECT * FROM cron.job ORDER BY jobid'), jobs);
    await db.exec(schedulingStub);
  });

  await test('inspection is read-only, excludes stored contents, and does not require SELECT on log rows', async () => {
    await db.exec(`CREATE ROLE inspection_reader;
      GRANT USAGE ON SCHEMA cron, net TO inspection_reader;
      GRANT SELECT ON cron.job TO inspection_reader;`);
    const before = await logState();
    await db.exec('BEGIN READ ONLY; SET LOCAL ROLE inspection_reader');
    try {
      const result = await db.query(inspection);
      assert.equal(result.rows.length, 1);
      assert.equal(result.rows[0].inspection.relations.length, 2);
      assert.equal((await rows('SHOW transaction_read_only'))[0].transaction_read_only, 'on');
      assert.doesNotMatch(JSON.stringify(result), /notification-job-sentinel|rollback-cron|rollback-http|PERFORM 1/);
      await assert.rejects(db.query('SELECT * FROM cron.job_run_details'), (error) => error.code === '42501');
    } finally {
      await db.exec('ROLLBACK');
    }
    assert.deepEqual(await logState(), before);
  });

  await test('native TRUNCATE RESTRICT rejects foreign-key cascades without removing linked data', async () => {
    await db.exec(`CREATE TABLE public.business_log_link (
      log_id bigint REFERENCES cron.job_run_details(runid)
    );
    INSERT INTO public.business_log_link SELECT runid FROM cron.job_run_details;`);
    const before = await logState();
    const linked = await rows('SELECT * FROM public.business_log_link');
    await assert.rejects(db.exec(cleanup), (error) => error.code === '0A000');
    await db.exec('ROLLBACK');
    assert.deepEqual(await logState(), before);
    assert.deepEqual(await rows('SELECT * FROM public.business_log_link'), linked);
  });

  console.log(`1..${passed}`);
  console.log('PostgreSQL/PGlite validates the complete SQL and transaction behavior; cron.schedule is a named-upsert stub, not the pg_cron worker. No production database is accessed.');
} finally {
  await db.close();
}
